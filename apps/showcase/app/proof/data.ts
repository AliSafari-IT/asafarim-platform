interface WorkspaceManifest {
  workspaces: Array<Omit<WorkspaceCard, "label" | "githubUrl" | "commitUrl" | "liveUrl">>;
  npmDependencies: string[];
}

/**
 * Reads apps/showcase/public-data/workspace.json — generated from git
 * history by scripts/generate-workspace-manifest.mjs on every push to main.
 * Workspace packages are never published, so their package.json semver is
 * never bumped; the last commit that touched each folder is the real
 * version, and that's what this surfaces.
 */
function readWorkspaceManifest(): WorkspaceManifest {
  const filePath = path.join(REPO_ROOT, "apps", "showcase", "public-data", "workspace.json");
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8")) as WorkspaceManifest;
  } catch {
    return { workspaces: [], npmDependencies: [] };
  }
}

export function getWorkspaceCards(): WorkspaceCard[] {
  return readWorkspaceManifest().workspaces.map((entry) => {
    const surface = entry.kind === "app" ? APP_SURFACES[entry.folder] : undefined;
    return {
      ...entry,
      label: surface?.label ?? entry.name,
      githubUrl: `${GITHUB_TREE}/${entry.folder}`,
      commitUrl: `${GITHUB_COMMIT}/${entry.sha}`,
      liveUrl: surface?.url ?? null,
    };
  });
}

// The npm account every @asafarim/* package is published from. Matching on
// the maintainer's username (never the email the search API also returns)
// keeps unrelated packages that merely mention "asafarim" out.
const NPM_MAINTAINER = "asafarim.be";
const NPM_SEARCH_URL = "https://registry.npmjs.org/-/v1/search?text=asafarim&size=250";
// api.npmjs.org caps a single range query at 18 months; walk back in
// windows until one comes back empty (i.e. before the first publish).
const DOWNLOAD_WINDOW_DAYS = 540;
const MAX_DOWNLOAD_WINDOWS = 8;
const NPM_REVALIDATE_SECONDS = 6 * 60 * 60;

interface NpmSearchObject {
  downloads?: { weekly?: number };
  package: {
    name: string;
    version: string;
    description?: string;
    date: string;
    maintainers?: Array<{ username?: string }>;
    links?: { npm?: string; repository?: string; homepage?: string };
  };
}

/** "git+https://github.com/X/y.git#main" -> "https://github.com/X/y" */
function normalizeRepoUrl(raw: string | undefined): string | null {
  if (!raw) return null;
  const cleaned = raw.replace(/^git\+/, "").replace(/#.*$/, "").replace(/\.git$/, "");
  return /^https:\/\/github\.com\//i.test(cleaned) ? cleaned : null;
}

function isoDay(date: Date): string {
  return date.toISOString().slice(0, 10);
}

async function getAllTimeDownloads(name: string): Promise<number | null> {
  const DAY = 24 * 60 * 60 * 1000;
  // npm's counts lag a day; today's window would always read as partial.
  let end = new Date(Date.now() - DAY);
  let total = 0;
  try {
    for (let i = 0; i < MAX_DOWNLOAD_WINDOWS; i++) {
      const start = new Date(end.getTime() - (DOWNLOAD_WINDOW_DAYS - 1) * DAY);
      const res = await fetchWithTimeout(
        `https://api.npmjs.org/downloads/point/${isoDay(start)}:${isoDay(end)}/${name}`,
        8000,
        NPM_REVALIDATE_SECONDS
      );
      if (!res.ok) return i === 0 ? null : total;
      const { downloads = 0 } = (await res.json()) as { downloads?: number };
      if (downloads === 0) break;
      total += downloads;
      end = new Date(start.getTime() - DAY);
    }
    return total;
  } catch {
    return null;
  }
}

/** Runs async work with bounded concurrency so ~35 packages don't trip npm's rate limit. */
async function mapWithConcurrency<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index]);
    }
  });
  await Promise.all(workers);
  return results;
}

/**
 * Every package published from the @asafarim npm account, discovered live
 * from the public registry search — a new publish shows up here without a
 * code change. Version and weekly downloads come from the search index,
 * all-time downloads from api.npmjs.org. Cached 6h; any failure renders as
 * "not yet measured" rather than a made-up number.
 */
export async function getNpmPortfolio(): Promise<NpmPortfolio> {
  const measuredAt = new Date().toISOString().slice(0, 10);
  const usedHere = new Set(readWorkspaceManifest().npmDependencies);
  try {
    const res = await fetchWithTimeout(NPM_SEARCH_URL, 8000, NPM_REVALIDATE_SECONDS);
    if (!res.ok) return { packages: [], totalDownloads: null, measuredAt, freshness: "not-yet-measured" };
    const { objects = [] } = (await res.json()) as { objects?: NpmSearchObject[] };
    const owned = objects.filter((o) => o.package.maintainers?.some((m) => m.username === NPM_MAINTAINER));

    const packages = await mapWithConcurrency(owned, 6, async (o): Promise<NpmPackageCard> => ({
      name: o.package.name,
      version: o.package.version,
      description: o.package.description ?? "",
      lastPublished: o.package.date.slice(0, 10),
      downloads: await getAllTimeDownloads(o.package.name),
      weeklyDownloads: o.downloads?.weekly ?? null,
      npmUrl: o.package.links?.npm ?? `https://www.npmjs.com/package/${o.package.name}`,
      repoUrl: normalizeRepoUrl(o.package.links?.repository),
      homepageUrl: o.package.links?.homepage ?? null,
      usedHere: usedHere.has(o.package.name),
    }));

    packages.sort((a, b) => (b.downloads ?? -1) - (a.downloads ?? -1) || a.name.localeCompare(b.name));
    const known = packages.filter((p) => p.downloads !== null);
    return {
      packages,
      totalDownloads: known.length ? known.reduce((sum, p) => sum + (p.downloads ?? 0), 0) : null,
      measuredAt,
      freshness: packages.length ? "live" : "not-yet-measured",
    };
  } catch {
    return { packages: [], totalDownloads: null, measuredAt, freshness: "not-yet-measured" };
  }
}
