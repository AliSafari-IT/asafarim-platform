/**
 * Public engineering-proof data contract.
 *
 * Everything exported here is explicitly allow-listed and safe to render on
 * a public page. It answers "what backs this claim, when was it true, and
 * how was it measured" — never "what is the live state of the system right
 * now." See docs/proof-board-plan.md for the rules this file must follow.
 *
 * Hard rule: do not add a field here that carries a hostname, IP, port,
 * database name/URL, secret, internal log line, or admin-only endpoint.
 * If you're unsure whether a fact is safe to publish, it isn't — ask first.
 */
import fs from "node:fs";
import path from "node:path";

export type Freshness = "live" | "last-known" | "not-yet-measured";

export interface ProofMetric {
  label: string;
  value: string;
  method: string;
  measuredAt: string; // ISO date — always the actual measurement time, never "now"
  freshness: Freshness;
}

export interface WorkspaceCard {
  name: string;
  /** Short human label — the product name for apps, the package name for packages. */
  label: string;
  kind: "package" | "app";
  folder: string;
  description: string;
  /** Last commit that touched the folder — the only version an unpublished workspace has. */
  sha: string;
  date: string;
  since: string;
  commits: number;
  dependents: number;
  githubUrl: string;
  commitUrl: string;
  liveUrl: string | null;
}

export interface NpmPackageCard {
  name: string;
  version: string;
  description: string;
  lastPublished: string;
  /** All-time downloads, or null when api.npmjs.org could not be reached. */
  downloads: number | null;
  weeklyDownloads: number | null;
  npmUrl: string;
  repoUrl: string | null;
  homepageUrl: string | null;
  /** Also a dependency of this monorepo, not only published from elsewhere. */
  usedHere: boolean;
}

export interface NpmPortfolio {
  packages: NpmPackageCard[];
  totalDownloads: number | null;
  measuredAt: string;
  freshness: Freshness;
}

